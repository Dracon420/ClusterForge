"""Phase 3 gate: the launch model must round-trip real command lines exactly.

Nothing writes here. This proves that parsing and re-rendering a launch line is
lossless BEFORE any code is allowed to generate a StartServer.bat, because a
flag silently dropped in that round-trip is a server that comes back without
-ServerPlatform=ALL, and no Xbox player can join it.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.importer import latest_launch_line, read_start_bat  # noqa: E402
from core.launch import LaunchConfig, build_start_bat, extract_from_bat  # noqa: E402

failures = 0


def check(label, ok, detail=""):
    global failures
    print(f"  {'OK  ' if ok else 'FAIL'} {label}{(' — ' + detail) if detail else ''}")
    if not ok:
        failures += 1


SOURCES = []

entry = latest_launch_line("TheIsland")
if entry:
    SOURCES.append(("Island / DSM live launch line", entry[1]))

for label, install, bat in (
    ("Island / StartServer.bat", r"D:\Servers\TheIsland", r"D:\Servers\TheIsland\StartServer.bat"),
    ("Svartalfheim / StartServer.bat", r"Z:\Svartalfhiem", r"Z:\StartServer.bat"),
):
    got = read_start_bat(install, bat)
    if got:
        SOURCES.append((label, got[1]))

print("=" * 78)
print("1. LOSSLESS ROUND-TRIP")
print("=" * 78)
for label, cmdline in SOURCES:
    cfg = LaunchConfig.parse(cmdline)
    rendered = cfg.render()
    check(label, rendered == cmdline.strip(),
          "" if rendered == cmdline.strip() else f"\n     in : {cmdline!r}\n     out: {rendered!r}")

print()
print("=" * 78)
print("2. PARSED VALUES")
print("=" * 78)
for label, cmdline in SOURCES:
    s = LaunchConfig.parse(cmdline).summary()
    print(f"  {label}")
    print(f"     map {s['map_name']}  port {s['port']}  rcon {s['rcon_port']}  "
          f"mods {s['mod_count']}  platform {s['platform']}")
    print(f"     switches: {', '.join(s['switches'])}")

print()
print("=" * 78)
print("3. CRITICAL FLAGS SURVIVE")
print("=" * 78)
# These are not optional: -ServerPlatform=ALL with -WinLiveMaxPlayers is what
# lets Xbox players connect. -converttostore must NOT reappear -- it is a
# one-time migration flag.
#
# -preventHibernation is checked only where the live script still carries it.
# It was mandatory while Der Dino Finder was installed; that mod came off every
# map on 2026-09-16 and hibernation went back on, so REQUIRING the flag here
# would have this test fail for doing exactly what was asked. What still must
# hold is the round trip: a flag that goes in comes out.
CONDITIONAL = ("preventHibernation",)
for label, cmdline in SOURCES:
    cfg = LaunchConfig.parse(cmdline)
    r = cfg.render()
    for flag in ("ServerPlatform=ALL", "WinLiveMaxPlayers", "usestore"):
        check(f"{label}: {flag}", flag.lower() in r.lower())
    for flag in CONDITIONAL:
        if flag.lower() in cmdline.lower():
            check(f"{label}: {flag} survives", flag.lower() in r.lower())
        else:
            print(f"  --   {label}: {flag} not in use here")
    check(f"{label}: no -converttostore", "converttostore" not in r.lower())

print()
print("=" * 78)
print("4. MOD LIST EDITING PRESERVES EVERYTHING ELSE")
print("=" * 78)
for label, cmdline in SOURCES:
    cfg = LaunchConfig.parse(cmdline)
    before_mods = cfg.mods
    before_switches = set(s.lower() for s in cfg.switches())
    before_port = cfg.resolve("port")

    # Reorder and drop one, the way the UI will.
    new_mods = list(reversed(before_mods))[:-1]
    cfg.set_mods(new_mods)

    after = LaunchConfig.parse(cfg.render())
    check(f"{label}: mod list applied",
          after.mods == new_mods, f"{len(after.mods)} vs {len(new_mods)}")
    check(f"{label}: switches unchanged",
          set(s.lower() for s in after.switches()) == before_switches)
    check(f"{label}: port unchanged", after.resolve("port") == before_port)
    check(f"{label}: order preserved exactly", after.mods == new_mods)

print()
print("=" * 78)
print("5. GENERATED BAT RE-PARSES IDENTICALLY")
print("=" * 78)
EXE = r"D:\Servers\TheIsland\ShooterGame\Binaries\Win64\ArkAscendedServer.exe"
for label, cmdline in SOURCES:
    text = build_start_bat(EXE, cmdline, header="generated by ArkPanel")
    got = extract_from_bat(text)
    check(f"{label}: bat parses back", got is not None)
    if got:
        exe, back = got
        check(f"{label}: exe preserved", exe == EXE)
        check(f"{label}: cmdline preserved", back == cmdline.strip(),
              "" if back == cmdline.strip() else f"\n     out: {back!r}")

print()
if failures:
    print(f"RESULT: {failures} FAILURE(S) — do not generate start scripts")
    sys.exit(1)
print("RESULT: PASS — launch model is lossless, safe to generate start scripts")
